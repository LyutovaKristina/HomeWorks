public class Calculator {

    public int add (int num1, int num2){
        return num1 + num2;
    }

    public int sub (int num2, int num1) {
        return num2 - num1;
    }

    public int mul (int num1, int num2){
        return num1 * num2;
    }
    public int div(int num1, int num2){
        return num1 / num2 ;
    }
    public int errorMult (int num1, int num2){
        return num1 * num1 ;
    }
}

